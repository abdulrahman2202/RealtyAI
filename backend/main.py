from __future__ import annotations

import asyncio
import logging
import os
from contextlib import asynccontextmanager
from pathlib import Path

from chromadb.errors import ChromaError
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from backend.api import routes
from backend.deployment import readiness
from backend.snapshot import SnapshotError, recover_from_environment

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env", override=False)


@asynccontextmanager
async def lifespan(application: FastAPI):
    application.state.snapshot_ready = False
    try:
        application.state.snapshot_result = await asyncio.to_thread(recover_from_environment)
        application.state.snapshot_ready = True
        logging.getLogger("uvicorn.error").info("Chroma snapshot startup: %s", application.state.snapshot_result["status"])
    except SnapshotError:
        application.state.snapshot_result = {"status": "failed"}
        logging.getLogger("uvicorn.error").warning("Chroma snapshot recovery failed; readiness is unavailable.")
    yield


app = FastAPI(
    title="RealtyAI API",
    description=(
        "REST API for the RealtyAI AI agent. Exposes Retrieval-Augmented "
        "Generation (RAG) over the local property dataset, with answers "
        "generated by Groq."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

# ── CORS ──────────────────────────────────────────────────────────────
# Allowed origins are read from the CORS_ORIGINS environment variable
# (comma-separated). Wildcard origins are not used with credentials enabled.
_cors_origins_raw = os.getenv(
    "CORS_ORIGINS", "http://localhost:3000,http://localhost:8000"
)
_cors_origins = [o.strip() for o in _cors_origins_raw.split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=_cors_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ── Routers ───────────────────────────────────────────────────────────
app.include_router(routes.router, prefix="/api")


@app.middleware("http")
async def require_recovered_database(request, call_next):
    if (os.getenv("REALTYAI_SNAPSHOT_ENDPOINT") and not getattr(app.state, "snapshot_ready", False)
            and request.url.path in {"/ready", "/api/chat"}):
        return JSONResponse(status_code=503, content={"detail": "The approved RAG database or offline model is not ready."})
    return await call_next(request)


# ── Endpoints ─────────────────────────────────────────────────────────


@app.get(
    "/health",
    summary="Health check",
    description=(
        "Returns application status and basic service information. "
        "This endpoint does not call the LLM API."
    ),
)
async def health() -> dict[str, str]:
    """Health check endpoint."""
    return {
        "status": "healthy",
        "service": "RealtyAI",
        "version": "1.0.0",
    }


@app.get("/ready", summary="Check approved database and offline model readiness")
def ready() -> dict:
    try:
        return readiness()
    except (ChromaError, KeyError, OSError, RuntimeError, TypeError, ValueError):
        raise HTTPException(status_code=503, detail="The approved RAG database or offline model is not ready.") from None
